// Langsamer Testlauf (Ticket 21): Tabelleninhalt und Bearbeiten gegen ein PostgreSQL aus embedded-postgres auf einem
// Zufallsport.

import * as fs from 'node:fs';
import * as path from 'node:path';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import type { CommandArgs, CommandName, CommandResult, DbChangeSet } from '../../src/shared/types';
import { createTestCore, type TestCore } from '../support/core';
import { PG_DATABASE, PG_PASSWORD, PG_USER, startPostgres, type TestPostgres } from '../support/postgres';
import { useTempDirs } from '../support/tempDir';

const WELCOME = 'Welcome to Codium';
const NUMERIC = '12345678901234567890.1234567890';
const BIG = '9007199254740993';
const JSON_TEXT = '{"b": 1,  "a": [1, 2.50]}';

describe('Datenbank: Tabelleninhalt und Bearbeiten', () => {
  const tempDir = useTempDirs();
  let server: TestPostgres;
  let test: TestCore;
  let windowId: number;
  let id: string;

  beforeAll(async () => {
    server = await startPostgres();
    expect(server.processes()).toBeGreaterThan(0);
  });

  afterAll(async () => {
    await server?.stop();
    if (server) expect(server.processes()).toBe(0);
  });

  beforeEach(async () => {
    await server.sql(`
      DROP SCHEMA IF EXISTS shop CASCADE;
      CREATE SCHEMA shop;
      SET TIME ZONE 'Europe/Zurich';
      CREATE TABLE shop.items (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL DEFAULT 'unnamed',
        price numeric(30,10),
        big bigint,
        at timestamptz,
        doc json,
        docb jsonb,
        data bytea,
        note text
      );
      INSERT INTO shop.items (name, price, big, at)
        SELECT 'item ' || lpad(g::text, 4, '0'), g, g, '2026-01-01 00:00:00+00'::timestamptz + g * interval '1 hour'
        FROM generate_series(1, 1200) g;
      UPDATE shop.items SET price = '${NUMERIC}', big = ${BIG}, doc = '${JSON_TEXT}', docb = '${JSON_TEXT}', data = '\\x000102'::bytea WHERE id = 7;
      CREATE TABLE shop.parents (id int PRIMARY KEY);
      CREATE TABLE shop.children (id int PRIMARY KEY, parent int REFERENCES shop.parents(id));
      INSERT INTO shop.parents VALUES (1);
      INSERT INTO shop.children VALUES (1, 1);
      CREATE TABLE shop.log (at timestamptz, message text);
      CREATE VIEW shop.cheap AS SELECT id, name FROM shop.items WHERE price < 10;
    `);
    const project = path.join(tempDir(), 'alpha');
    fs.mkdirSync(project);
    test = createTestCore(path.join(tempDir(), 'data'), { dbConnectTimeoutMs: 5000 });
    await test.core.start();
    await call(test.ports.windows.windowTitled(WELCOME), 'app.openProject', { path: project });
    windowId = test.ports.windows.windowTitled('alpha – Codium');
    id = (
      await call(windowId, 'db.saveConnection', {
        connection: { name: 'Shop', host: '127.0.0.1', port: server.port, database: PG_DATABASE, user: PG_USER, ssl: false, askPassword: false },
        password: PG_PASSWORD,
      })
    ).id;
  });

  function call<K extends CommandName>(window: number, name: K, ...args: CommandArgs<K>): Promise<CommandResult<K>> {
    return test.core.router.call({ windowId: window }, name, ...args);
  }

  const rows = (table: string, extra: { offset?: number; sort?: { column: string; direction: 'asc' | 'desc' }; filter?: string } = {}) =>
    call(windowId, 'db.tableRows', { id, schema: 'shop', table, offset: extra.offset ?? 0, ...(extra.sort ? { sort: extra.sort } : {}), ...(extra.filter !== undefined ? { filter: extra.filter } : {}) });
  const submit = (table: string, changes: Partial<DbChangeSet>) =>
    call(windowId, 'db.submitChanges', { id, schema: 'shop', table, changes: { updates: [], inserts: [], deletes: [], ...changes } });
  const one = async (sql: string) => (await server.sql(sql)).rows[0];

  it('liefert Seiten zu 500 nach dem Primärschlüssel, sortiert in der Datenbank und filtert', async () => {
    const info = await call(windowId, 'db.tableInfo', { id, schema: 'shop', table: 'items' });
    expect(info.primaryKey).toEqual(['id']);
    expect(info.readOnlyReason).toBeUndefined();
    const first = await rows('items');
    expect(first.rows).toHaveLength(500);
    expect(first.hasMore).toBe(true);
    expect(first.rows[0][0]).toBe('1');
    expect(first.rows[499][0]).toBe('500');
    const last = await rows('items', { offset: 1000 });
    expect(last.rows).toHaveLength(200);
    expect(last.hasMore).toBe(false);
    expect(last.rows[199][0]).toBe('1200');

    const sorted = await rows('items', { sort: { column: 'name', direction: 'desc' } });
    expect(sorted.rows[0][1]).toBe('item 1200');
    const filtered = await rows('items', { filter: "name LIKE 'item 000%' AND id <> 3 -- ein Kommentar" });
    expect(filtered.rows.map((r) => r[0])).toEqual(['1', '2', '4', '5', '6', '7', '8', '9']);
    await expect(rows('items', { filter: 'gibt_es_nicht = 1' })).rejects.toMatchObject({ code: 'DB_FAILED', message: expect.stringMatching(/gibt_es_nicht/) });
    await expect(rows('items', { sort: { column: 'x"; DROP TABLE shop.items; --', direction: 'asc' } })).rejects.toMatchObject({ code: 'INVALID_PARAMS' });
  });

  it('überträgt Werte verlustfrei; bytea erscheint als Länge', async () => {
    const info = await call(windowId, 'db.tableInfo', { id, schema: 'shop', table: 'items' });
    const col = (name: string) => info.columns.findIndex((c) => c.name === name);
    expect(info.columns[col('data')]).toMatchObject({ binary: true, json: false });
    expect(info.columns[col('docb')]).toMatchObject({ binary: false, json: true });
    const row = (await rows('items', { filter: 'id = 7' })).rows[0];
    expect(row[col('price')]).toBe(NUMERIC);
    expect(row[col('big')]).toBe(BIG);
    expect(row[col('doc')]).toBe(JSON_TEXT);
    expect(row[col('docb')]).toBe('{"a": [1, 2.50], "b": 1}');
    expect(row[col('at')]).toBe((await one("SELECT at::text AS v FROM shop.items WHERE id = 7")).v);
    expect(row[col('data')]).toBe('3');
    expect(row[col('note')]).toBeNull();

    // Die ursprünglichen Werte im Vergleich: grosse Zahlen, Zeitpunkt und JSON treffen die Zeile.
    await submit('items', {
      updates: [
        {
          key: { id: '7' },
          original: { price: row[col('price')], big: row[col('big')], at: row[col('at')], doc: row[col('doc')], docb: row[col('docb')] },
          values: { price: '0.0000000001', big: '-9223372036854775808', at: '2030-05-06 07:08:09.123456+02', doc: '[]', docb: '{"x": null}' },
        },
      ],
    });
    const after = await one("SELECT price::text, big::text, doc::text, docb::text, (at = '2030-05-06 07:08:09.123456+02') AS same FROM shop.items WHERE id = 7");
    expect(after).toEqual({ price: '0.0000000001', big: '-9223372036854775808', doc: '[]', docb: '{"x": null}', same: true });
    await expect(submit('items', { updates: [{ key: { id: '7' }, original: {}, values: { data: 'x' } }] })).rejects.toMatchObject({ code: 'INVALID_PARAMS' });
  });

  it('führt Update, Insert (Standardwert, Identität, NULL) und Delete in einer Transaktion aus', async () => {
    await submit('items', {
      updates: [
        { key: { id: '1' }, original: { name: 'item 0001' }, values: { name: 'Erster' } },
        { key: { id: '2' }, original: { name: 'item 0002', note: null }, values: { name: 'Zweiter', note: 'mit Notiz' } },
      ],
      inserts: [{ values: {} }, { values: { name: 'Neu', note: null, price: '1.5' } }],
      deletes: [{ key: { id: '3' } }],
    });
    expect(await one('SELECT name FROM shop.items WHERE id = 1')).toEqual({ name: 'Erster' });
    expect(await one('SELECT name, note FROM shop.items WHERE id = 2')).toEqual({ name: 'Zweiter', note: 'mit Notiz' });
    expect(await one('SELECT count(*)::int AS n FROM shop.items WHERE id = 3')).toEqual({ n: 0 });
    // Leere neue Zeile: Standardwert und Identität; ausdrückliches NULL bleibt NULL.
    const inserted = (await server.sql('SELECT id::int, name, note, price::text FROM shop.items WHERE id > 1200 ORDER BY id')).rows;
    expect(inserted).toEqual([
      { id: 1201, name: 'unnamed', note: null, price: null },
      { id: 1202, name: 'Neu', note: null, price: '1.5000000000' },
    ]);
  });

  it('rollt bei einem Fehler alles zurück; fremd geänderte oder gelöschte Zeilen brechen ab', async () => {
    // Verletzter Fremdschlüssel: auch die gültige Änderung davor wird zurückgerollt.
    await submit('parents', { inserts: [{ values: { id: '2' } }] });
    await expect(
      submit('children', {
        updates: [{ key: { id: '1' }, original: { parent: '1' }, values: { parent: '2' } }],
        inserts: [{ values: { id: '5', parent: '99' } }],
      }),
    ).rejects.toMatchObject({ code: 'DB_FAILED', message: expect.stringMatching(/foreign key/) });
    expect(await one('SELECT parent FROM shop.children WHERE id = 1')).toEqual({ parent: 1 });

    // Fremd geänderte Zelle (dieselbe Spalte): nichts gespeichert, auch nicht die andere Änderung.
    await server.sql("UPDATE shop.items SET name = 'von aussen' WHERE id = 10");
    await expect(
      submit('items', {
        updates: [
          { key: { id: '11' }, original: { name: 'item 0011' }, values: { name: 'meins' } },
          { key: { id: '10' }, original: { name: 'item 0010' }, values: { name: 'meins' } },
        ],
      }),
    ).rejects.toMatchObject({ code: 'DB_FAILED', message: expect.stringMatching(/changed or deleted in the meantime/) });
    expect(await one('SELECT name FROM shop.items WHERE id = 11')).toEqual({ name: 'item 0011' });
    // Eine andere Spalte derselben Zeile darf sich geändert haben.
    await submit('items', { updates: [{ key: { id: '10' }, original: { note: null }, values: { note: 'ok' } }] });

    // Inzwischen gelöschte Zeile: Update und Delete brechen ab.
    await server.sql('DELETE FROM shop.items WHERE id = 20');
    await expect(submit('items', { updates: [{ key: { id: '20' }, original: { name: 'item 0020' }, values: { name: 'x' } }] })).rejects.toMatchObject({
      code: 'DB_FAILED',
    });
    await expect(submit('items', { deletes: [{ key: { id: '20' } }] })).rejects.toMatchObject({ code: 'DB_FAILED', message: expect.stringMatching(/already deleted/) });
  });

  it('macht Tabellen ohne Primärschlüssel und Views schreibgeschützt', async () => {
    const log = await call(windowId, 'db.tableInfo', { id, schema: 'shop', table: 'log' });
    expect(log.readOnlyReason).toMatch(/no primary key/);
    expect((await rows('log')).rows).toEqual([]);
    const view = await call(windowId, 'db.tableInfo', { id, schema: 'shop', table: 'cheap' });
    expect(view).toMatchObject({ kind: 'view', readOnlyReason: 'Views are read-only.' });
    // Zeile 7 trägt den grossen Preis und fällt aus der View.
    expect((await rows('cheap')).rows.length).toBe(8);
    await expect(submit('log', { inserts: [{ values: { message: 'x' } }] })).rejects.toMatchObject({ code: 'DB_FAILED' });
    await expect(submit('cheap', { deletes: [{ key: { id: '1' } }] })).rejects.toMatchObject({ code: 'DB_FAILED' });
    // Das Speichern erscheint als Fortschritt in der Statusleiste.
    test.events.sent.length = 0;
    await submit('items', { updates: [{ key: { id: '1' }, original: {}, values: { note: 'n' } }] });
    expect(test.events.sent.some((e) => e.name === 'app.progress' && (e.payload as { title?: string }).title === 'Saving changes…')).toBe(true);
  });
});
