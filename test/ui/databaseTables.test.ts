// Teststelle 2: Tabelleninhalt und Bearbeiten (Ticket 21) gegen ein PostgreSQL aus embedded-postgres auf einem
// Zufallsport.

import * as fs from 'node:fs';
import * as path from 'node:path';
import type { Locator, Page } from 'playwright-core';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { launchCodium, prepareAppState } from '../support/launchApp';
import { PG_DATABASE, PG_PASSWORD, PG_USER, startPostgres, type TestPostgres } from '../support/postgres';
import { useTempDirs } from '../support/tempDir';

function node(page: Page, name: string): Locator {
  return page.getByRole('tree', { name: 'Database' }).getByRole('treeitem', { name, exact: true });
}

function cell(page: Page, column: string, row: number): Locator {
  return page.getByRole('grid', { name: 'store.items' }).getByRole('gridcell', { name: `${column} ${row}`, exact: true });
}

describe('Tabelleninhalt', () => {
  const tempDir = useTempDirs();
  let server: TestPostgres;

  beforeAll(async () => {
    server = await startPostgres();
  });

  afterAll(async () => {
    await server?.stop();
    if (server) expect(server.processes()).toBe(0);
  });

  beforeEach(async () => {
    await server.sql(`
      DROP SCHEMA IF EXISTS store CASCADE;
      CREATE SCHEMA store;
      CREATE TABLE store.items (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL DEFAULT 'unnamed', note text);
      INSERT INTO store.items (name) SELECT 'item ' || g FROM generate_series(1, 600) g;
    `);
  });

  /** Startet Codium mit einer Verbindung (über den Dialog) und öffnet die Tabelle store.items. */
  async function openItems() {
    const project = path.join(tempDir(), 'Shop');
    fs.mkdirSync(project);
    const dataRoot = tempDir();
    prepareAppState(dataRoot, { openProjects: [project], recentProjects: [project] });
    const codium = await launchCodium({ dataRoot });
    const page = await codium.page('Shop – Codium');
    await page.getByRole('navigation').getByRole('button', { name: 'Database', exact: true }).click({ timeout: 15_000 });
    await page.getByRole('button', { name: 'New Connection' }).click();
    const dialog = page.getByRole('dialog', { name: 'New Connection' });
    await dialog.getByLabel('Name', { exact: true }).fill('Shop DB');
    await dialog.getByLabel('Host', { exact: true }).fill('127.0.0.1');
    await dialog.getByLabel('Port', { exact: true }).fill(String(server.port));
    await dialog.getByLabel('Database', { exact: true }).fill(PG_DATABASE);
    await dialog.getByLabel('User', { exact: true }).fill(PG_USER);
    await dialog.getByLabel('Password', { exact: true }).fill(PG_PASSWORD);
    await dialog.getByRole('button', { name: 'OK' }).click();
    await dialog.waitFor({ state: 'detached' });
    await node(page, 'Shop DB').dblclick();
    await node(page, PG_DATABASE).dblclick();
    await node(page, 'store').dblclick({ timeout: 20_000 });
    await node(page, 'items').dblclick({ timeout: 20_000 });
    await expect.poll(() => cell(page, 'name', 1).innerText(), { timeout: 20_000 }).toBe('item 1');
    return { codium, page };
  }

  async function editCell(page: Page, column: string, row: number, value: string) {
    await cell(page, column, row).dblclick();
    const input = cell(page, column, row).locator('input');
    await input.fill(value);
    await input.press('Enter');
  }

  it('ändert Zellen in mehreren Zeilen, fügt eine Zeile hinzu, löscht eine; „Submit“ speichert alles, mit Fortschritt', async () => {
    const { codium, page } = await openItems();
    try {
      await editCell(page, 'name', 1, 'Erster');
      await editCell(page, 'note', 2, 'Notiz zwei');
      expect(await cell(page, 'name', 1).getAttribute('class')).toContain('changed');
      await cell(page, 'name', 3).click();
      await page.getByRole('button', { name: 'Delete Row' }).click();
      expect(await page.getByRole('row', { name: 'Row 3', exact: true }).getAttribute('class')).toContain('deleted');
      await page.getByRole('button', { name: 'Add Row' }).click();
      await editCell(page, 'name', 501, 'Neue Zeile');

      // Während des Speicherns (die Tabelle ist kurz gesperrt) zeigt die Statusleiste Fortschritt.
      await server.sql('BEGIN; LOCK TABLE store.items IN ACCESS EXCLUSIVE MODE;');
      await cell(page, 'name', 1).click();
      await page.keyboard.press('Control+Enter');
      await expect.poll(() => page.locator('.status-progress-text').allTextContents(), { timeout: 15_000 }).toContain('Saving changes…');
      await server.sql('COMMIT');
      await expect.poll(() => page.locator('.status-progress-text').count(), { timeout: 15_000 }).toBe(0);

      // Nach dem Neuladen ist alles da.
      await expect.poll(() => cell(page, 'name', 1).innerText(), { timeout: 15_000 }).toBe('Erster');
      expect(await cell(page, 'name', 1).getAttribute('class')).not.toContain('changed');
      const rows = (await server.sql('SELECT id, name, note FROM store.items WHERE id <= 3 OR id > 600 ORDER BY id')).rows;
      expect(rows).toEqual([
        { id: 1, name: 'Erster', note: null },
        { id: 2, name: 'item 2', note: 'Notiz zwei' },
        { id: 601, name: 'Neue Zeile', note: null },
      ]);
    } finally {
      await codium.close();
    }
  });

  it('verwirft eine Änderung mit „Revert“; mit offener Änderung fragt der Seitenwechsel nach', async () => {
    const { codium, page } = await openItems();
    try {
      await editCell(page, 'name', 5, 'weg damit');
      await page.getByRole('button', { name: 'Revert' }).click();
      expect(await cell(page, 'name', 5).innerText()).toBe('item 5');
      expect(await cell(page, 'name', 5).getAttribute('class')).not.toContain('changed');

      await editCell(page, 'name', 6, 'offen');
      await page.getByRole('button', { name: 'Next' }).click();
      const question = page.getByRole('dialog', { name: 'Unsaved Changes' });
      await question.waitFor();
      await question.getByRole('button', { name: 'Cancel' }).click();
      expect(await page.getByLabel('Rows', { exact: true }).innerText()).toBe('Rows 1–500');
      expect(await cell(page, 'name', 6).innerText()).toBe('offen');

      await page.getByRole('button', { name: 'Next' }).click();
      await question.getByRole('button', { name: 'Discard' }).click();
      await expect.poll(() => page.getByLabel('Rows', { exact: true }).innerText(), { timeout: 15_000 }).toBe('Rows 501–600');
      expect((await server.sql("SELECT count(*)::int AS n FROM store.items WHERE name = 'offen'")).rows[0].n).toBe(0);
    } finally {
      await codium.close();
    }
  });
});
